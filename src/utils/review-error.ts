// 需要从 msg 中解析具体字段的错误码
const FIELD_ERROR_CODES = new Set([108000015, 110000001, 101000001]);

const FIELD_KEYS = Object.keys(FIELD_LABELS).sort(
  (a, b) => b.length - a.length
);

/** 从后端 msg（如 "invalid field type: course.code"）解析出中文字段名 */
function fieldLabelFromMessage(msg?: string): string {
  if (!msg) return '';
  const lower = msg.toLowerCase();
  for (const key of FIELD_KEYS) {
    if (lower.includes(key)) return FIELD_LABELS[key];
  }
  return '';
}

/**
 * 综合 code + 后端 msg 生成用户提示。
 *
 * @param code 后端业务错误码
 * @param msg  后端返回的 msg（可选，用于字段级错误细化）
 * @returns 中文提示；未收录的 code 返回空串
 */
export function errorMessageOf(code?: number, msg?: string): string {
  if (typeof code !== 'number') return '';

  if (FIELD_ERROR_CODES.has(code)) {
    const label = fieldLabelFromMessage(msg);
    if (label) {
      if (code === 108000015) {
        return `课程信息不完整：缺少${label}，请用「修改后通过」补全后再通过`;
      }
      return `请求参数有误：${label} 不符合要求`;
    }
  }

  return ERROR_MESSAGES[code] || '';
}

/** 仅按错误码取提示（拿不到 msg 时使用），兼容旧调用 */
export function reviewErrorMessage(code?: number): string {
  return errorMessageOf(code);
}

